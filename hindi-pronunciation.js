function improveHindiPronunciation(text) {
    let result = text;

    const words = Object.keys(pronunciation)
        .sort((a, b) => b.length - a.length);

    for (const word of words) {
        const pattern = new RegExp(
            `(?<![\\p{L}\\p{M}])${word}(?![\\p{L}\\p{M}])`,
            "gu"
        );

        result = result.replace(pattern, pronunciation[word]);
    }

    return result;
}

