function improveRomanPronunciation(text) {
    const keys = Object.keys(pronunciation).sort((a, b) => b.length - a.length);
    const pattern = new RegExp(
        "\\b(" + keys.map(k => k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|") + ")\\b",
        "gi"
    );

    return String(text).replace(pattern, word => pronunciation[word.toLowerCase()]);
}

